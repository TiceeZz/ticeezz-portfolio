export function getV3CaseStudy(slug) {
  const idx = V3_CASE_STUDIES.findIndex((c) => c.slug === slug);
  if (idx === -1) return null;
  return {
    study: V3_CASE_STUDIES[idx],
    prev: idx > 0 ? V3_CASE_STUDIES[idx - 1] : null,
    next: idx < V3_CASE_STUDIES.length - 1 ? V3_CASE_STUDIES[idx + 1] : null,
  };
}
